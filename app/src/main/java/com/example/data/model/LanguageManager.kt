    fun getString(key: String, languageCode: String): String {
        val langMap = translations[languageCode] ?: translations["en"]!!
        return langMap[key] ?: (translations["en"]?.get(key) ?: key)
    }

    fun isRtl(languageCode: String): Boolean {
        return languageCode == "ar" || languageCode == "ur"
    }

    fun getLanguagePromptName(code: String): String {
        return when (code) {
            "zh" -> "Mandarin Chinese"
            "hi" -> "Hindi"
            "es" -> "Spanish"
            "fr" -> "French"
            "ar" -> "Arabic"
            "bn" -> "Bengali"
            "pt" -> "Portuguese"
            "ru" -> "Russian"
            "ur" -> "Urdu"
            else -> "English"
        }
    }
